// Copies ../../deployments/*.json into src/deployments.ts so every package imports addresses from one place.
// Every file in deployments/ is picked up, keyed by its chainId: a chain without a file (Sepolia before its first
// deploy) is simply absent, so `deployments[id]` is undefined for it and nothing else changes.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

/** Deployment files in `dir` keyed by chain id (integer keys, so they serialise in ascending chain id order). */
export function collect(dir) {
  const all = {};
  for (const f of readdirSync(dir).filter((f) => f.endsWith(".json")).sort()) {
    const d = JSON.parse(readFileSync(join(dir, f), "utf8"));
    if (!Number.isInteger(d.chainId)) throw new Error(`${f}: no numeric chainId`);
    if (all[d.chainId]) throw new Error(`${f}: chain ${d.chainId} already read from another file`);
    all[d.chainId] = d;
  }
  return all;
}

export function render(all) {
  return (
    `// Generated by scripts/sync-deployments.mjs from deployments/*.json. Do not edit.\n` +
    `import type { Deployment } from "./types.js";\n\n` +
    `export const deployments: Record<number, Deployment> = ${JSON.stringify(all, null, 2)} as const as unknown as Record<number, Deployment>;\n`
  );
}

if (process.argv[1] && import.meta.url === pathToFileURL(process.argv[1]).href) {
  const here = dirname(fileURLToPath(import.meta.url));
  const all = collect(join(here, "../../../deployments"));
  writeFileSync(join(here, "../src/deployments.ts"), render(all));
  console.log(`deployments for chains: ${Object.keys(all).join(", ") || "(none)"}`);
}
