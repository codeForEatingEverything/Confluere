// Copies ../../deployments/*.json into src/deployments.ts so every package imports addresses from one place.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const dir = join(here, "../../../deployments");
const out = join(here, "../src/deployments.ts");
const all = {};
for (const f of readdirSync(dir).filter((f) => f.endsWith(".json"))) {
  const d = JSON.parse(readFileSync(join(dir, f), "utf8"));
  all[d.chainId] = d;
}
writeFileSync(
  out,
  `// Generated by scripts/sync-deployments.mjs from deployments/*.json. Do not edit.\n` +
    `import type { Deployment } from "./types.js";\n\n` +
    `export const deployments: Record<number, Deployment> = ${JSON.stringify(all, null, 2)} as const as unknown as Record<number, Deployment>;\n`,
);
console.log(`deployments for chains: ${Object.keys(all).join(", ") || "(none)"}`);
